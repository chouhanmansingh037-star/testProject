'use client';

import { useEffect } from 'react';
import { useAssistant, selectBusy } from '../store/assistant';
import { HomeView } from './HomeView';
import { SummaryView } from './SummaryView';
import { ThreadView } from './ThreadView';
import { Avatar, BackIcon, ChatIcon, CloseIcon, ExpandIcon, HomeIcon, InfoIcon } from './icons';

export function ApprovalsPanel({ itemCount }: { itemCount: number | null }) {
  const open = useAssistant((s) => s.open);
  const expanded = useAssistant((s) => s.expanded);
  const view = useAssistant((s) => s.view);
  const greetingLoading = useAssistant((s) => s.greeting.status === 'loading');
  const busy = useAssistant(selectBusy);
  const { openPanel, closePanel, toggleExpanded, goTo, loadGreeting } = useAssistant.getState();

  useEffect(() => {
    if (!open) return;
    const onKey = (e: globalThis.KeyboardEvent) => {
      if (e.key === 'Escape') closePanel();
    };
    document.addEventListener('keydown', onKey);
    return () => document.removeEventListener('keydown', onKey);
  }, [open, closePanel]);

  const replay = () => {
    goTo('home');
    void loadGreeting(true);
  };

  return (
    <>
      {open && (
        <div className={`panel${expanded ? ' panel--expanded' : ''}`} role="dialog" aria-label="Approvals assistant" aria-busy={busy}>
          <header className="panel__header">
            <Avatar size={36} />
            <h1 className="panel__title">Approvals</h1>
            <div className="panel__tools">
              <button type="button" className="icon-btn" aria-label="About this assistant" title="Answers are generated by an AI model and may be wrong. Verify before approving.">
                <InfoIcon />
              </button>
              <button type="button" className="icon-btn" aria-label={expanded ? 'Shrink panel' : 'Expand panel'} aria-pressed={expanded} onClick={toggleExpanded}>
                <ExpandIcon />
              </button>
              <button type="button" className="icon-btn" aria-label="Close assistant" onClick={closePanel}>
                <CloseIcon />
              </button>
            </div>
          </header>

          <nav className="panel__crumbs" aria-label="Assistant navigation">
            <button type="button" className="crumb" onClick={() => goTo('home')} aria-current={view === 'home' ? 'page' : undefined}>
              {view === 'home' ? <HomeIcon /> : <BackIcon />} Approvals
            </button>
            <button type="button" className="link-amber" onClick={replay} disabled={greetingLoading}>
              Replay Greeting
            </button>
          </nav>

          <div className="panel__body">
            {view === 'home' && <HomeView />}
            {view === 'summary' && <SummaryView />}
            {(view === 'talk' || view === 'help' || view === 'teach') && <ThreadView key={view} view={view} />}
          </div>

          <footer className="panel__footer">
            <span>{itemCount === null ? '…' : itemCount} folders / items</span>
            <span className="muted">AI-generated. Verify before acting.</span>
          </footer>
        </div>
      )}
      <button
        type="button"
        className="launcher"
        aria-label={open ? 'Hide approvals assistant' : 'Open approvals assistant'}
        aria-expanded={open}
        onClick={() => (open ? closePanel() : openPanel())}
      >
        {open ? <CloseIcon /> : <ChatIcon />}
      </button>
    </>
  );
}
